/**
 * One-command local demo (`pnpm start`). Collapses the manual multi-step Docker
 * Compose flow documented in GETTING_STARTED.md — copy .env.example, hand-edit
 * passwords, `docker compose up`, copy those same passwords into env vars for
 * `pnpm dev:sample` — into a single command a first-time reader can run without
 * touching any file themselves:
 *
 *   1. Checks Docker is actually running (clear EN+JA message if not, then exits).
 *   2. Generates `deploy/compose/.env` with random passwords IF one doesn't already
 *      exist — never overwrites a real one a reader may have customized.
 *   3. Starts Postgres/Valkey/Keycloak via `docker compose up -d --wait`, then polls
 *      Keycloak specifically (it has no defined healthcheck — see
 *      docker-compose.yml's comment) the same way scripts/dev-server.ts's own
 *      self-managed-Keycloak path already does.
 *   4. Runs `pnpm dev:sample` as a child process, passing it the AIAF_* env vars
 *      derived from the .env file just generated/read — the reader never has to
 *      copy a password between two files by hand.
 *
 * Idempotent and safe to re-run: an existing `.env` is reused as-is (not
 * regenerated), and `docker compose up -d --wait` is a no-op against
 * already-running containers.
 */
import { execFileSync, spawn } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..");
const composeDir = join(repoRoot, "deploy", "compose");
const envPath = join(composeDir, ".env");
const composeFile = join(composeDir, "docker-compose.yml");

const KEYCLOAK_URL = "http://127.0.0.1:8180";

function genPassword(): string {
  return randomBytes(18).toString("base64url"); // URL-safe: never needs shell-quoting
}

function ensureDockerRunning(): void {
  try {
    execFileSync("docker", ["info"], { stdio: "ignore" });
  } catch {
    console.error("Docker doesn't seem to be running.");
    console.error("→ Open the Docker Desktop app, wait for it to fully start, then run `pnpm start` again.");
    console.error("");
    console.error("（日本語）Dockerが起動していないようです。");
    console.error("→ Docker Desktopアプリを開き、完全に起動するのを待ってから、もう一度 `pnpm start` を実行してください。");
    process.exit(1);
  }
}

interface ComposeEnv {
  POSTGRES_USER: string;
  POSTGRES_PASSWORD: string;
  POSTGRES_DB: string;
  VALKEY_PASSWORD: string;
  KEYCLOAK_ADMIN_PASSWORD: string;
}

const ENV_LINE_PATTERN = /^([A-Z_]+)=(.*)$/;

function ensureEnvFile(): ComposeEnv {
  if (!existsSync(envPath)) {
    const generated: ComposeEnv = {
      POSTGRES_USER: "factory",
      POSTGRES_PASSWORD: genPassword(),
      POSTGRES_DB: "factory",
      VALKEY_PASSWORD: genPassword(),
      KEYCLOAK_ADMIN_PASSWORD: genPassword(),
    };
    const content = [
      "# Auto-generated by `pnpm start` on first run — random passwords, local use only.",
      `POSTGRES_USER=${generated.POSTGRES_USER}`,
      `POSTGRES_PASSWORD=${generated.POSTGRES_PASSWORD}`,
      `POSTGRES_DB=${generated.POSTGRES_DB}`,
      "",
      `VALKEY_PASSWORD=${generated.VALKEY_PASSWORD}`,
      "",
      `KEYCLOAK_ADMIN_PASSWORD=${generated.KEYCLOAK_ADMIN_PASSWORD}`,
      "",
    ].join("\n");
    writeFileSync(envPath, content);
    console.log(`generated ${envPath} with random passwords (first run only)`);
    return generated;
  }

  const values: Partial<ComposeEnv> = {};
  for (const line of readFileSync(envPath, "utf-8").split("\n")) {
    const match = line.match(ENV_LINE_PATTERN);
    if (match) values[match[1] as keyof ComposeEnv] = match[2] ?? "";
  }
  for (const key of ["POSTGRES_USER", "POSTGRES_PASSWORD", "VALKEY_PASSWORD", "KEYCLOAK_ADMIN_PASSWORD"] as const) {
    if (!values[key]) throw new Error(`${envPath} exists but is missing ${key} — fill it in (see .env.example) or delete the file to regenerate it.`);
  }
  return { POSTGRES_DB: values.POSTGRES_DB ?? "factory", ...values } as ComposeEnv;
}

function startCompose(): void {
  console.log("Starting Postgres, Valkey, and Keycloak (docker compose)...");
  execFileSync("docker", ["compose", "--env-file", envPath, "-f", composeFile, "up", "-d", "--wait", "--wait-timeout", "90"], {
    stdio: "inherit",
    cwd: repoRoot,
  });
}

async function waitForKeycloak(): Promise<void> {
  console.log("Waiting for Keycloak to finish starting...");
  for (let i = 0; i < 60; i++) {
    try {
      if ((await fetch(`${KEYCLOAK_URL}/realms/master`)).ok) return;
    } catch {
      // not up yet
    }
    await new Promise((resolve) => setTimeout(resolve, 2000));
  }
  throw new Error("Keycloak did not become ready in time — check `docker compose logs keycloak`");
}

function startDevServer(env: ComposeEnv): never {
  console.log("Starting the demo app (pnpm dev:sample)...\n");
  const child = spawn("pnpm", ["dev:sample"], {
    cwd: repoRoot,
    stdio: "inherit",
    env: {
      ...process.env,
      AIAF_PG_USER: env.POSTGRES_USER,
      AIAF_PG_PASSWORD: env.POSTGRES_PASSWORD,
      AIAF_KEYCLOAK_URL: KEYCLOAK_URL,
      AIAF_KEYCLOAK_ADMIN_PASSWORD: env.KEYCLOAK_ADMIN_PASSWORD,
    },
  });
  child.on("exit", (code) => process.exit(code ?? 0));
  child.on("error", (error) => {
    console.error(error);
    process.exit(1);
  });
  // Keep this process alive until the child exits — the `exit` handler above
  // is what actually terminates us; nothing further to do on this side.
  return undefined as never;
}

async function main(): Promise<void> {
  ensureDockerRunning();
  const env = ensureEnvFile();
  startCompose();
  await waitForKeycloak();
  startDevServer(env);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
