import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import type { AddressInfo } from "node:net";
import { parseAppSpecYaml } from "@aiappfactory/app-spec";
import { createCompanySdk, SdkGatewayError } from "@aiappfactory/company-sdk";
import { quoteIdent } from "@aiappfactory/expr";
import { applyMigration, applyPlatformBootstrap, compileAppSpec } from "@aiappfactory/spec-compiler";
import type { FastifyInstance } from "fastify";
import pg from "pg";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { AppRegistry } from "../../src/registry.js";
import { buildServer } from "../../src/server.js";

/**
 * Proves the FULL M1 backend path works end to end: an HTTP client that only knows
 * Company SDK's contract → sdk-gateway (holds the only DB credentials) → a real
 * PostgreSQL server whose RLS policies were generated by spec-compiler. This is the
 * same scenario spec-compiler's own integration test proves at the SQL layer, run
 * one layer up — through the actual network boundary Company SDK is supposed to be
 * the only way across (01_ARCHITECTURE §5.1).
 *
 * Same local-Postgres requirement as spec-compiler's integration test — see its
 * header comment. Run via `pnpm test:integration`.
 */

const PGHOST = "127.0.0.1";
const PGPORT = 5432;
const PGUSER = process.env.PG_TEST_SUPERUSER ?? "hayato";
const TEST_DB = `aiaf_sdk_gateway_test_${Date.now()}`;
const APP_ROLE_PASSWORD = "test-only-not-a-real-secret";

const templatesDir = join(import.meta.dirname, "..", "..", "..", "..", "templates");

let adminPool: pg.Pool;
let appRolePool: pg.Pool;
let server: FastifyInstance;
let gatewayUrl: string;
let roleName: string;
let appId: string;

let deptSales: string;
let deptOther: string;
let alice: string;
let bob: string;
let carol: string;
let dave: string;

beforeAll(async () => {
  const bootstrapPool = new pg.Pool({ host: PGHOST, port: PGPORT, user: PGUSER, database: "postgres" });
  await bootstrapPool.query(`CREATE DATABASE ${quoteIdent(TEST_DB)}`);
  await bootstrapPool.end();

  adminPool = new pg.Pool({ host: PGHOST, port: PGPORT, user: PGUSER, database: TEST_DB });
  await applyPlatformBootstrap(adminPool);

  deptSales = randomUUID();
  deptOther = randomUUID();
  alice = randomUUID();
  bob = randomUUID();
  carol = randomUUID();
  dave = randomUUID();

  await adminPool.query(`INSERT INTO public.departments (id) VALUES ($1), ($2)`, [deptSales, deptOther]);
  await adminPool.query(
    `INSERT INTO public.users (id, department_id) VALUES ($1, $2), ($3, $2), ($4, $2), ($5, $6)`,
    [alice, deptSales, bob, carol, dave, deptOther]
  );

  const source = readFileSync(join(templatesDir, "sales-daily-report", "app.yaml"), "utf-8");
  const parsed = parseAppSpecYaml(source);
  if (!parsed.ok) throw new Error(`template failed to validate: ${JSON.stringify(parsed.issues)}`);
  appId = parsed.spec.metadata.id;

  const migration = compileAppSpec(parsed.spec, { rolePassword: APP_ROLE_PASSWORD });
  roleName = migration.roleName;
  await applyMigration(adminPool, migration);

  appRolePool = new pg.Pool({ host: PGHOST, port: PGPORT, user: roleName, password: APP_ROLE_PASSWORD, database: TEST_DB });

  const registry = new AppRegistry();
  registry.register(appId, { spec: parsed.spec, pool: appRolePool, schemaName: migration.schemaName });

  server = buildServer(registry);
  await server.listen({ port: 0, host: "127.0.0.1" });
  const address = server.server.address() as AddressInfo;
  gatewayUrl = `http://127.0.0.1:${address.port}`;
}, 30_000);

afterAll(async () => {
  await server?.close();
  await appRolePool?.end();
  if (adminPool) {
    if (roleName) {
      await adminPool.query(`DROP OWNED BY ${quoteIdent(roleName)}`).catch(() => {});
      await adminPool.query(`DROP ROLE IF EXISTS ${quoteIdent(roleName)}`).catch(() => {});
    }
    await adminPool.end();
  }
  const cleanupPool = new pg.Pool({ host: PGHOST, port: PGPORT, user: PGUSER, database: "postgres" });
  await cleanupPool.query(`DROP DATABASE IF EXISTS ${quoteIdent(TEST_DB)} WITH (FORCE)`).catch(() => {});
  await cleanupPool.end();
}, 30_000);

function sdkFor(userId: string, department: string, roles: string[]) {
  return createCompanySdk({ gatewayUrl, appId, ctx: { userId, department, roles } });
}

describe("Company SDK → sdk-gateway → Postgres RLS, over real HTTP", () => {
  it("alice (sales_member) creates a report and it comes back with author auto-injected", async () => {
    const row = await sdkFor(alice, deptSales, ["sales_member"])
      .database.entity("DailyReport")
      .create({ customerName: "Acme", amount: 100 });
    expect(row.author).toBe(alice); // client never sent "author" — the gateway injected it
    expect(row.customerName).toBe("Acme");
  });

  it("bob (sales_member) creates his own report", async () => {
    await sdkFor(bob, deptSales, ["sales_member"]).database.entity("DailyReport").create({ customerName: "Beta", amount: 200 });
  });

  it("read:own — alice's list() shows only her own rows", async () => {
    const rows = await sdkFor(alice, deptSales, ["sales_member"]).database.entity("DailyReport").list();
    expect(rows.length).toBeGreaterThan(0);
    expect(rows.every((r) => r.author === alice)).toBe(true);
  });

  it("read:dept — carol (sales_manager, same dept) sees both alice's and bob's rows", async () => {
    const rows = await sdkFor(carol, deptSales, ["sales_manager"]).database.entity("DailyReport").list();
    const authors = new Set(rows.map((r) => r.author));
    expect(authors.has(alice)).toBe(true);
    expect(authors.has(bob)).toBe(true);
  });

  it("read:dept — dave (sales_manager, different dept) sees nothing", async () => {
    const rows = await sdkFor(dave, deptOther, ["sales_manager"]).database.entity("DailyReport").list();
    expect(rows.length).toBe(0);
  });

  it("update:own — alice can update her own row via the SDK", async () => {
    const [own] = await sdkFor(alice, deptSales, ["sales_member"]).database.entity("DailyReport").list();
    const updated = await sdkFor(alice, deptSales, ["sales_member"])
      .database.entity("DailyReport")
      .update(own!.id as string, { amount: 999 });
    expect(Number(updated.amount)).toBe(999);
  });

  it("update — attempting to update someone else's row surfaces as 404 (S-05: hide existence, not just deny)", async () => {
    const [bobsRow] = await sdkFor(carol, deptSales, ["sales_manager"]).database.entity("DailyReport").list();
    const asAlice = sdkFor(alice, deptSales, ["sales_member"]);
    await expect(asAlice.database.entity("DailyReport").update(bobsRow!.id as string, { amount: 1 })).rejects.toMatchObject({
      status: 404,
    });
  });

  it("delete — rejected as 403: no role in this Spec is granted delete", async () => {
    const [row] = await sdkFor(alice, deptSales, ["sales_member"]).database.entity("DailyReport").list();
    const error = await sdkFor(alice, deptSales, ["sales_member"])
      .database.entity("DailyReport")
      .delete(row!.id as string)
      .catch((e) => e);
    expect(error).toBeInstanceOf(SdkGatewayError);
    expect((error as SdkGatewayError).status).toBe(403);
  });

  it("create — sending an unknown field name is rejected as 400", async () => {
    const error = await sdkFor(alice, deptSales, ["sales_member"])
      .database.entity("DailyReport")
      .create({ notAField: 1 } as never)
      .catch((e) => e);
    expect(error).toBeInstanceOf(SdkGatewayError);
    expect((error as SdkGatewayError).status).toBe(400);
  });

  it("an unregistered app id surfaces as 404", async () => {
    const sdk = createCompanySdk({
      gatewayUrl,
      appId: "ghost-app",
      ctx: { userId: alice, department: deptSales, roles: ["sales_member"] },
    });
    const err = await sdk.database.entity("DailyReport").list().catch((e) => e);
    expect(err).toBeInstanceOf(SdkGatewayError);
    expect((err as SdkGatewayError).status).toBe(404);
  });
});
